#!/usr/bin/env python3
"""Builds gpu/vk/vk_lang_pt_br.inc (the Portuguese dictionary, compiled into the game) from assets/lang/pt-BR.tsv.

Run it after editing the .tsv:  python nx2/gen_lang.py
The .inc is a byte array (no string literal: no compiler's limit on one). A lang/pt-BR.tsv beside the game is read instead
of it when there is one (gpu/vk/vk_lang.h)."""
import os, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, 'assets', 'lang', 'pt-BR.tsv')
dst = os.path.join(root, 'gpu', 'vk', 'vk_lang_pt_br.inc')
data = open(src, 'rb').read()
if data.startswith(b'\xef\xbb\xbf'):
    data = data[3:]
data = data.replace(b'\r\n', b'\n')
lines = []
for i in range(0, len(data), 24):
    lines.append('    ' + ','.join(str(b) for b in data[i:i + 24]) + ',')
with open(dst, 'w', newline='\n') as f:
    f.write('// Generated by nx2/gen_lang.py from assets/lang/pt-BR.tsv: do not edit.\n')
    f.write('inline const unsigned char kPtBr[] = {\n')
    f.write('\n'.join(lines) + '\n')
    f.write('    0};\n')
print(dst, len(data), 'bytes')
